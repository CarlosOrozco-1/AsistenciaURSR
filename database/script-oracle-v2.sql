-- SECCIÓN 1: ELIMINACIÓN DE OBJETOS EXISTENTES
-- --------------------------------------------------------------------------------
-- Descripción: Garantiza un entorno limpio para cada ejecución del script.
PROMPT Eliminando objetos existentes...
DECLARE
    -- Este bloque PL/SQL elimina en orden: procedimientos, vistas y tablas.
BEGIN
    FOR rec IN (SELECT object_name, object_type FROM user_objects WHERE object_type IN ('PROCEDURE', 'VIEW', 'TABLE')) LOOP
        IF rec.object_type = 'PROCEDURE' THEN
            EXECUTE IMMEDIATE 'DROP PROCEDURE ' || rec.object_name;
        ELSIF rec.object_type = 'VIEW' THEN
            EXECUTE IMMEDIATE 'DROP VIEW ' || rec.object_name;
        ELSIF rec.object_type = 'TABLE' THEN
            EXECUTE IMMEDIATE 'DROP TABLE ' || rec.object_name || ' CASCADE CONSTRAINTS';
        END IF;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('No se encontraron objetos para eliminar o ocurrió un error menor.');
END;
/

