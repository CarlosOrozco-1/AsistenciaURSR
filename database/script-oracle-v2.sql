-- SECCIÓN 5: CREACIÓN DE VISTAS
-- --------------------------------------------------------------------------------
PROMPT Creando vistas para simplificar consultas...
CREATE OR REPLACE VIEW V_REPORTE_ASISTENCIA_DIARIA AS
SELECT
    TRUNC(RA.FECHA_HORA_REGISTRO) AS FECHA,
    E.NUMERO_CARNET,
    E.NOMBRES || ' ' || E.APELLIDOS AS NOMBRE_ESTUDIANTE,
    C.NOMBRE_CURSO,
    S.CODIGO_SECCION,
    (SELECT FECHA_HORA_REGISTRO FROM REGISTROS_ASISTENCIA WHERE ID_INSCRIPCION_FK = I.ID_INSCRIPCION AND TIPO_REGISTRO = 'ENTRADA' AND TRUNC(FECHA_HORA_REGISTRO) = TRUNC(RA.FECHA_HORA_REGISTRO)) AS HORA_ENTRADA,
    (SELECT FECHA_HORA_REGISTRO FROM REGISTROS_ASISTENCIA WHERE ID_INSCRIPCION_FK = I.ID_INSCRIPCION AND TIPO_REGISTRO = 'SALIDA' AND TRUNC(FECHA_HORA_REGISTRO) = TRUNC(RA.FECHA_HORA_REGISTRO)) AS HORA_SALIDA,
    CAT.NOMBRES || ' ' || CAT.APELLIDOS AS NOMBRE_CATEDRATICO,
    P.NOMBRE_PERIODO
FROM REGISTROS_ASISTENCIA RA
JOIN INSCRIPCIONES I ON RA.ID_INSCRIPCION_FK = I.ID_INSCRIPCION
JOIN ESTUDIANTES E ON I.ID_ESTUDIANTE_FK = E.ID_ESTUDIANTE
JOIN CURSOS_IMPARTIDOS CI ON I.ID_CURSO_IMPARTIDO_FK = CI.ID_CURSO_IMPARTIDO
JOIN CURSOS C ON CI.ID_CURSO_FK = C.ID_CURSO
JOIN SECCIONES S ON CI.ID_SECCION_FK = S.ID_SECCION
JOIN CATEDRATICOS CAT ON CI.ID_CATEDRATICO_FK = CAT.ID_CATEDRATICO
JOIN PERIODOS_ACADEMICOS P ON CI.ID_PERIODO_FK = P.ID_PERIODO
GROUP BY TRUNC(RA.FECHA_HORA_REGISTRO), I.ID_INSCRIPCION, E.NUMERO_CARNET, E.NOMBRES, E.APELLIDOS, C.NOMBRE_CURSO, S.CODIGO_SECCION, CAT.NOMBRES, CAT.APELLIDOS, P.NOMBRE_PERIODO;

-- --------------------------------------------------------------------------------
-- SECCIÓN 6: CREACIÓN DE PROCEDIMIENTOS ALMACENADOS
-- --------------------------------------------------------------------------------
PROMPT Creando procedimientos almacenados para la lógica de negocio...
-- MEJORA: Procedimiento adaptado a la lógica de negocio del QR.
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_ASISTENCIA (
    p_codigo_qr           IN VARCHAR2,
    p_numero_carnet       IN VARCHAR2,
    p_tipo_registro       IN VARCHAR2, -- 'ENTRADA' o 'SALIDA'
    p_resultado           OUT VARCHAR2,
    p_detalle             OUT VARCHAR2
) AS
    v_id_estudiante         NUMBER;
    v_id_curso_impartido    NUMBER;
    v_id_inscripcion        NUMBER;
    v_conteo_entrada        NUMBER;
    v_conteo_salida         NUMBER;
BEGIN
    -- 1. Validar el código QR y obtener el curso impartido
    BEGIN
        SELECT ID_CURSO_IMPARTIDO_FK INTO v_id_curso_impartido
        FROM SESIONES_CLASE_QR
        WHERE CODIGO_QR = p_codigo_qr AND ESTADO = 'A';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            p_resultado := 'ERROR';
            p_detalle := 'Código QR inválido o expirado.';
            RETURN;
    END;

    -- 2. Obtener ID del estudiante
    BEGIN
        SELECT ID_ESTUDIANTE INTO v_id_estudiante FROM ESTUDIANTES WHERE NUMERO_CARNET = p_numero_carnet;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            p_resultado := 'ERROR';
            p_detalle := 'Número de carnet no encontrado.';
            RETURN;
    END;

    -- 3. Obtener ID de la inscripción
    BEGIN
        SELECT ID_INSCRIPCION INTO v_id_inscripcion
        FROM INSCRIPCIONES
        WHERE ID_ESTUDIANTE_FK = v_id_estudiante
          AND ID_CURSO_IMPARTIDO_FK = v_id_curso_impartido;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            p_resultado := 'ERROR';
            p_detalle := 'El estudiante no está inscrito en este curso.';
            RETURN;
    END;

    -- 4. Aplicar lógica de Entrada/Salida
    SELECT COUNT(*) INTO v_conteo_entrada
    FROM REGISTROS_ASISTENCIA
    WHERE ID_INSCRIPCION_FK = v_id_inscripcion
      AND TRUNC(FECHA_HORA_REGISTRO) = TRUNC(SYSDATE)
      AND TIPO_REGISTRO = 'ENTRADA';

    SELECT COUNT(*) INTO v_conteo_salida
    FROM REGISTROS_ASISTENCIA
    WHERE ID_INSCRIPCION_FK = v_id_inscripcion
      AND TRUNC(FECHA_HORA_REGISTRO) = TRUNC(SYSDATE)
      AND TIPO_REGISTRO = 'SALIDA';

    IF p_tipo_registro = 'ENTRADA' THEN
        IF v_conteo_entrada > 0 THEN
            p_resultado := 'AVISO';
            p_detalle := 'La entrada ya fue registrada para hoy.';
            RETURN;
        END IF;
    ELSIF p_tipo_registro = 'SALIDA' THEN
        IF v_conteo_entrada = 0 THEN
            p_resultado := 'ERROR';
            p_detalle := 'Debe registrar una entrada antes de registrar una salida.';
            RETURN;
        END IF;
        IF v_conteo_salida > 0 THEN
            p_resultado := 'AVISO';
            p_detalle := 'La salida ya fue registrada para hoy.';
            RETURN;
        END IF;
    ELSE
        p_resultado := 'ERROR';
        p_detalle := 'Tipo de registro inválido.';
        RETURN;
    END IF;

    -- 5. Insertar el registro
    INSERT INTO REGISTROS_ASISTENCIA (ID_INSCRIPCION_FK, TIPO_REGISTRO)
    VALUES (v_id_inscripcion, p_tipo_registro);

    COMMIT;
    p_resultado := 'EXITO';
    p_detalle := 'Registro de ' || p_tipo_registro || ' guardado correctamente.';

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_resultado := 'ERROR';
        p_detalle := 'Ocurrió un error inesperado: ' || SQLERRM;
END;
/

-- --------------------------------------------------------------------------------
-- SECCIÓN 7: MÓDULO DE AUDITORÍA GENÉRICO
-- --------------------------------------------------------------------------------
-- Descripción: En lugar de un trigger por tabla, se crea un único procedimiento
-- que puede auditar CUALQUIER tabla. Los triggers se vuelven simples y solo se
-- encargan de llamar a este procedimiento, haciendo el sistema mucho más fácil
-- de mantener y extender.
PROMPT Creando módulo de auditoría genérico...
CREATE OR REPLACE PROCEDURE SP_AUDITAR_TABLA (
    p_nombre_tabla       IN VARCHAR2,
    p_tipo_accion        IN VARCHAR2,
    p_id_registro        IN VARCHAR2,
    p_valores_anteriores IN CLOB,
    p_valores_nuevos     IN CLOB,
    p_usuario_app        IN VARCHAR2 DEFAULT NULL
) AS
BEGIN
    INSERT INTO AUDITORIA (
        NOMBRE_TABLA,
        ID_REGISTRO_AFECTADO,
        TIPO_ACCION,
        VALORES_ANTERIORES,
        VALORES_NUEVOS,
        USUARIO_APP
    ) VALUES (
        p_nombre_tabla,
        p_id_registro,
        p_tipo_accion,
        p_valores_anteriores,
        p_valores_nuevos,
        p_usuario_app
    );
END;
/

-- --------------------------------------------------------------------------------
-- SECCIÓN 8: TRIGGERS DE AUDITORÍA SIMPLIFICADOS
-- --------------------------------------------------------------------------------
-- Descripción: Estos triggers ahora son muy simples. Su única responsabilidad
-- es recolectar la información del cambio y llamar al procedimiento genérico
-- SP_AUDITAR_TABLA.
PROMPT Creando triggers de auditoría...

CREATE OR REPLACE TRIGGER TRG_AUD_ESTUDIANTES
AFTER INSERT OR UPDATE OR DELETE ON ESTUDIANTES
FOR EACH ROW
DECLARE
    v_tipo_accion       VARCHAR2(10);
    v_valores_antiguos  CLOB;
    v_valores_nuevos    CLOB;
BEGIN
    IF INSERTING THEN
        v_tipo_accion := 'INSERT';
        v_valores_nuevos := 'CARNET: ' || :NEW.NUMERO_CARNET || ', NOMBRES: ' || :NEW.NOMBRES;
    ELSIF UPDATING THEN
        v_tipo_accion := 'UPDATE';
        v_valores_antiguos := 'CARNET: ' || :OLD.NUMERO_CARNET || ', NOMBRES: ' || :OLD.NOMBRES;
        v_valores_nuevos := 'CARNET: ' || :NEW.NUMERO_CARNET || ', NOMBRES: ' || :NEW.NOMBRES;
    ELSIF DELETING THEN
        v_tipo_accion := 'DELETE';
        v_valores_antiguos := 'CARNET: ' || :OLD.NUMERO_CARNET || ', NOMBRES: ' || :OLD.NOMBRES;
    END IF;

    SP_AUDITAR_TABLA(
        p_nombre_tabla => 'ESTUDIANTES',
        p_tipo_accion => v_tipo_accion,
        p_id_registro => NVL(TO_CHAR(:NEW.ID_ESTUDIANTE), TO_CHAR(:OLD.ID_ESTUDIANTE)),
        p_valores_anteriores => v_valores_antiguos,
        p_valores_nuevos => v_valores_nuevos
    );
END;
/

CREATE OR REPLACE TRIGGER TRG_AUD_REGISTROS_ASISTENCIA
AFTER INSERT ON REGISTROS_ASISTENCIA
FOR EACH ROW
BEGIN
    SP_AUDITAR_TABLA(
        p_nombre_tabla => 'REGISTROS_ASISTENCIA',
        p_tipo_accion => 'INSERT',
        p_id_registro => :NEW.ID_REGISTRO,
        p_valores_nuevos => 'INSCRIPCION_FK: ' || :NEW.ID_INSCRIPCION_FK || ', TIPO: ' || :NEW.TIPO_REGISTRO
    );
END;
